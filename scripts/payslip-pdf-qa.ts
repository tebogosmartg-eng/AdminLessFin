async function main() {
  const brandPng = pngDataUrl('public/icons/app-icon.png');

  // Case A: company logo provided (data URL — works offline)
  const withCompany = await generatePayslipPdf(baseFixture(brandPng));
  const withCompanyPath = join(outDir, 'payslip-company-logo.pdf');
  writeFileSync(withCompanyPath, Buffer.from(withCompany.output('arraybuffer')));
  const withCompanyPreviews = await rasterize(withCompanyPath, 'company-logo');

  // Case B: no company logo — employer name/address remain primary; AdminLess Fin only in footer
  const defaultBrand = await generatePayslipPdf(baseFixture(null));
  const defaultPath = join(outDir, 'payslip-default-brand.pdf');
  writeFileSync(defaultPath, Buffer.from(defaultBrand.output('arraybuffer')));
  const defaultPreviews = await rasterize(defaultPath, 'default-brand');

  // Text extraction structural checks on default brand PDF
  const buf = Buffer.from(defaultBrand.output('arraybuffer'));
  const asText = buf.toString('latin1');
  const checks = {
    deductionsHeaderIntact: /Deductions/.test(asText),
    amountHeaderIntact: /Amount/.test(asText),
    statutoryHeaderIntact: /Statutory/.test(asText),
    employerHeaderIntact: /Employer Contributions/.test(asText),
    brandFooter: /Generated by/.test(asText) && /AdminLess Fin/.test(asText),
    paymentSection: /Payment Information/.test(asText) || /Payment Method/.test(asText),
    fullAccount: /62000000001/.test(asText),
    branchCode: /250655/.test(asText),
    bankName: /FNB/.test(asText),
  };

  let extracted = '';
  try {
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
    const pdf = await pdfjs.getDocument({ data: new Uint8Array(buf) }).promise;
    const page = await pdf.getPage(1);
    const content = await page.getTextContent();
    extracted = content.items.map((i) => ('str' in i ? i.str : '')).join(' ');
  } catch {
    // optional
  }

  const report = {
    withCompanyPath,
    withCompanyPreviews,
    defaultPath,
    defaultPreviews,
    checks,
    extractedPreview: extracted.slice(0, 600),
    noStackedDeductions: extracted ? !/D e d u c t i o n s/.test(extracted) : null,
  };
  writeFileSync(join(outDir, 'qa-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));

  const failed = Object.entries(checks).filter(([, v]) => v === false);
  if (failed.length) throw new Error(`QA failed: ${failed.map(([k]) => k).join(', ')}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
