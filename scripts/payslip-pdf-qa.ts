/**
 * Visual QA harness for payslip PDF layout.
 * Generates fixture PDFs + PNG previews for manual inspection.
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatePayslipPdf } from '../src/lib/payrollDocuments';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outDir = join(root, 'tmp', 'payslip-qa');
mkdirSync(outDir, { recursive: true });

function pngDataUrl(relPath: string): string {
  const abs = join(root, relPath);
  if (!existsSync(abs)) throw new Error(`Missing ${abs}`);
  return `data:image/png;base64,${readFileSync(abs).toString('base64')}`;
}

async function rasterize(pdfPath: string, prefix: string): Promise<string[]> {
  const { pdf } = await import('pdf-to-img');
  const paths: string[] = [];
  let n = 0;
  for await (const image of await pdf(pdfPath, { scale: 2 })) {
    n += 1;
    const pngPath = join(outDir, `${prefix}-page-${n}.png`);
    writeFileSync(pngPath, image);
    paths.push(pngPath);
  }
  return paths;
}

