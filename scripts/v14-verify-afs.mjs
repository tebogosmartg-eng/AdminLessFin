import { readFileSync, writeFileSync } from 'fs';

function decodePdfText(bytes) {
  const raw = Buffer.from(bytes).toString('latin1');
  return [...raw.matchAll(/\((?:\\.|[^\\)])*\)/g)]
    .map((m) => m[0].slice(1, -1).replace(/\\n/g, '\n').replace(/\\([()\\])/g, '$1'))
    .join('\n');
}

const after = readFileSync('docs/enterprise-accounts-production/V14.0/evidence/AFS_V14_Meridian_after.pdf');
const text = decodePdfText(after);
writeFileSync('docs/enterprise-accounts-production/V14.0/evidence/AFS_V14_Meridian_after.txt', text);

const checks = [
  ['no Generated by', !text.includes('Generated by AdminLess Fin')],
  ['has AdminLess Fin brand', text.includes('AdminLess Fin')],
  ['has Nature of business heading', text.includes('1. Nature of business')],
  ['has Companies Act wording', text.includes('Companies Act of South Africa')],
  ['has negative parentheses', text.includes('(19,122,400.00)')],
  ['has Note 1. form', /Note 1\./.test(text)],
  ['has Approval section', text.includes('Approval of Annual Financial Statements')],
  ['has Supplementary Information', text.includes('Supplementary Information')],
  ['has comparative year 2025', text.includes('2025')],
  ['no Recognition - labels', !text.includes('Recognition -')],
  ['no header 0.00 Current assets', !/Current assets\n0\.00/.test(text)],
  ['no header 0.00 Equity and liabilities', !/Equity and liabilities\n0\.00/.test(text)],
];

for (const [label, ok] of checks) {
  console.log(ok ? 'PASS' : 'FAIL', label);
}
